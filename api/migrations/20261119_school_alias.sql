-- Additive school aliases. Caller owns BEGIN/COMMIT together with the seed import.
CREATE TABLE public."SchoolAlias" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "schoolId" bigint NOT NULL REFERENCES public."School"(id) ON DELETE CASCADE,
    alias text NOT NULL CHECK (length(btrim(alias)) > 0),
    "normalizedAlias" text NOT NULL CHECK ("normalizedAlias" ~ '^[a-z0-9]+( [a-z0-9]+)*$'),
    source text,
    "createdAt" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT "SchoolAlias_school_normalized_key" UNIQUE ("schoolId", "normalizedAlias")
);
ALTER TABLE public."SchoolAlias" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public."SchoolAlias" FROM PUBLIC;
DO $grants$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        REVOKE ALL ON public."SchoolAlias" FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        REVOKE ALL ON public."SchoolAlias" FROM authenticated;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
        GRANT SELECT ON public."SchoolAlias" TO service_role;
    END IF;
END
$grants$;
