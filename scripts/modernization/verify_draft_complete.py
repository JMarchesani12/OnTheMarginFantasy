def tests(engine, database, probe=False):
    covered=set()
    def observe(name, method):
        def wrapper(self, *args, **kwargs):
            covered.add(name)
            return method(self, *args, **kwargs)
        return wrapper
    repo_type=type('ObservedRepository',(DraftPickRepository,),{
        name:observe(name,method) for name,method in vars(DraftPickRepository).items()
        if callable(method) and not name.startswith('_')})
    repo=repo_type();service=DraftPickService(engine,repo);bob=UserActor(2,'bob');alice=UserActor(1,'alice')
    listener=psycopg2.connect(dbname=database,**LOCAL);listener.autocommit=True
    with listener.cursor() as cursor:cursor.execute('LISTEN draft_updated')
    def query(statement, **params):
        with engine.begin() as conn:
            result=conn.execute(text(statement),params)
            return result.mappings().all() if result.returns_rows else []
    def reset():
        with engine.begin() as conn:conn.exec_driver_sql(FIXTURE)
        messages()
    def messages():
        with listener.cursor() as cursor:cursor.execute('SELECT 1')
        listener.poll();items=list(listener.notifies);listener.notifies.clear();return items
    def state():
        with engine.connect() as conn:
            return {table:[dict(r._mapping) for r in conn.execute(text(f'SELECT * FROM "{table}" ORDER BY 1,2'))]
                    for table in ('League','LeagueMember','DraftState','DraftTurn','DraftPick','LeagueTeamSlot')}
    def expire():query('UPDATE "DraftState" SET "expiresAt"=now()-interval \'5 seconds\' WHERE "leagueId"=10')
    def auto():
        query('UPDATE "League" SET settings=jsonb_set(settings,\'{draft,timeoutAction}\',\'"AUTO-PICK"\') WHERE id=10');expire()
    def final():
        query('UPDATE "DraftState" SET "currentOverallPickNumber"=4,"currentMemberId"=11 WHERE "leagueId"=10')
    def expect(error, call, contains=None):
        try:call()
        except error as exc:
            if contains:assert contains in str(exc),(contains,str(exc))
        else:raise AssertionError('Expected '+error.__name__)
    def failure_after(fragment, call):
        before=state();triggered=[]
        def fail(conn,cursor,statement,params,context,many):
            if fragment in statement:triggered.append(True);raise RuntimeError('synthetic post-statement failure')
        event.listen(engine,'after_cursor_execute',fail)
        try:expect(RuntimeError,call)
        finally:event.remove(engine,'after_cursor_execute',fail)
        assert triggered and state()==before and not messages(),fragment
    try:
        reset()
        if probe:
            expire();return service.process_timeout_for_job(10)
        # Public lookups and native UUID casts; explicit membership does not open snapshots.
        assert service.is_supabase_user_in_league(10,'00000000-0000-4000-8000-000000000002')
        assert not service.is_supabase_user_in_league(10,'00000000-0000-4000-8000-000000000003')
        assert service.get_rounds(1)==12
        with engine.begin() as conn:
            assert service._member_id_for_draft_order(conn,10,2)==12
            expect(ValueError,lambda:service._member_id_for_draft_order(conn,10,99),'Missing LeagueMember')
        row=service.pick_live(bob,10,12,102,3)
        assert (row['memberId'],row['overallPickNumber'],row['roundNumber'],row['pickInRound'],row['nextMemberId'])==(12,2,1,2,12)
        slot=state()['LeagueTeamSlot'][0];assert (slot['acquiredWeek'],slot['acquiredVia'])==(3,'Draft')
        assert not messages()  # Existing nonterminal live publication is HTTP post-commit.
        # Actor authority, turn, expiry/grace, active ownership and duplicate pick rejection.
        for actor,member,error,fragment in ((alice,12,PermissionError,None),(bob,11,PermissionError,None),
                (bob,12,ValueError,'Not your turn')):
            reset()
            if fragment:query('UPDATE "DraftTurn" SET "memberId"=11 WHERE "leagueId"=10 AND "overallPickNumber"=2')
            before=state();expect(error,lambda:service.pick_live(actor,10,member,102),fragment);assert state()==before
        reset();expire();before=state();expect(ValueError,lambda:service.pick_live(bob,10,12,102),'expired');assert state()==before
        query('UPDATE "League" SET settings=jsonb_set(settings,\'{draft,graceSeconds}\',\'20\') WHERE id=10')
        assert service.pick_live(bob,10,12,102)['overallPickNumber']==2
        reset();query('INSERT INTO "LeagueTeamSlot" ("leagueId","memberId","sportTeamId","acquiredWeek") VALUES (10,11,102,1)')
        before=state();expect(ValueError,lambda:service.pick_live(bob,10,12,102),'already owned');assert state()==before
        reset();before=state();expect(ValueError,lambda:service.pick_live(bob,10,12,101),'conflict');assert state()==before
        # Native cap joins, duplicate memberships counted distinctly, season/global membership and dropped slot boundary.
        reset();query('INSERT INTO "SportTeam" VALUES (104,1,\'Conference Candidate\')')
        query('INSERT INTO "ConferenceMembership" VALUES (104,1,NULL,501),(101,1,2026,501)')
        query('UPDATE "SportConference" SET "maxTeamsPerOwner"=1')
        query('INSERT INTO "LeagueTeamSlot" ("leagueId","memberId","sportTeamId","acquiredWeek","droppedWeek") VALUES (10,12,101,1,4)')
        before=state();expect(ValueError,lambda:service.pick_live(bob,10,12,104,3),'1/1');assert state()==before
        assert service.pick_live(bob,10,12,104,4)['sportTeamId']==104
        reset();query('INSERT INTO "ConferenceMembership" VALUES (102,1,2025,501)')
        with engine.begin() as conn:assert service._get_conference_info_for_team(conn,10,102) is None
        # Manual jobs preserve count/snake/default week and native transactional pg_notify.
        reset();row=service.allocate_manual_for_job(10,12,102)
        assert row['overallPickNumber']==2 and state()['LeagueTeamSlot'][0]['acquiredWeek']==1
        notifications=messages();assert len(notifications)==1 and json.loads(notifications[0].payload)['reason']=='manual_pick'
        reset();query('DELETE FROM "DraftTurn" WHERE "leagueId"=10 AND "overallPickNumber">2')
        assert service.pick_live(bob,10,12,102)['draftComplete'] is True
        assert state()['DraftState'][0]['status']=='complete' and messages()
        reset();final();assert service.pick_live(alice,10,11,102)['draftComplete'] is True
        assert state()['League'][0]['status']=='Post-Draft' and messages()
        # Every write/notification boundary rolls back; native DB statement and deferred-commit failures too.
        for mode,fragment in (('live','INSERT INTO "DraftPick"'),('live','INSERT INTO "LeagueTeamSlot"'),
                ('live','"lastPickAt" = now()'),('manual','INSERT INTO "LeagueTeamSlot"'),
                ('manual','pg_notify'),('final','UPDATE "League"'),('final','pg_notify')):
            reset()
            if mode=='final':final()
            call=(lambda:service.allocate_manual_for_job(10,12,102)) if mode=='manual' else (lambda:service.pick_live(alice if mode=='final' else bob,10,11 if mode=='final' else 12,102))
            failure_after(fragment,call)
        for deferred in (False,True):
            reset();before=state()
            with engine.begin() as conn:
                conn.exec_driver_sql('''CREATE FUNCTION fail_allocation() RETURNS trigger LANGUAGE plpgsql AS $$
                    BEGIN RAISE EXCEPTION 'synthetic allocation failure'; END $$;''')
                if deferred:conn.exec_driver_sql('CREATE CONSTRAINT TRIGGER allocation_failure AFTER INSERT ON "LeagueTeamSlot" DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fail_allocation()')
                else:conn.exec_driver_sql('CREATE TRIGGER allocation_failure BEFORE INSERT ON "LeagueTeamSlot" FOR EACH ROW EXECUTE FUNCTION fail_allocation()')
            expect(DBAPIError,lambda:service.allocate_manual_for_job(10,12,102));assert state()==before and not messages()
        # Separate transaction revokes ownership between precheck and guarded INSERT SELECT.
        reset();before=state();other=engine_for(database,'otm-pick-revoke');changed=[]
        def revoke(conn,cursor,statement,params,context,many):
            if 'INSERT INTO "DraftPick"' in statement and not changed:
                changed.append(True)
                with other.begin() as separate:separate.execute(text('UPDATE "LeagueMember" SET "userId"=1 WHERE id=12'))
        event.listen(engine,'before_cursor_execute',revoke)
        try:expect(PermissionError,lambda:service.pick_live(bob,10,12,102))
        finally:event.remove(engine,'before_cursor_execute',revoke);other.dispose()
        before['LeagueMember'][1]['userId']=1;assert changed==[True] and state()==before
        # Timeout no-ops, native expiration alias, rotation over unpicked holes, last-turn clock.
        for clause in ('status=\'paused\'','"expiresAt"=NULL','"expiresAt"=now()+interval \'60 seconds\'',
                       '"currentOverallPickNumber"=5'):
            reset();query('UPDATE "DraftState" SET '+clause+' WHERE "leagueId"=10');before=state()
            assert service.process_timeout_for_job(10) is None and state()==before
        reset();expire();query('UPDATE "League" SET settings=jsonb_set(settings,\'{draft,graceSeconds}\',\'20\') WHERE id=10');before=state()
        assert service.process_timeout_for_job(10) is None and state()==before
        reset();expire();row=service.process_timeout_for_job(10)
        assert (row['timedOutMemberId'],row['movedToOverallPickNumber'],row['nextMemberId'])==(12,4,12)
        assert [r['memberId'] for r in state()['DraftTurn'][:4]]==[11,12,11,12] and not messages()
        reset();query('INSERT INTO "DraftPick" ("leagueId","overallPickNumber","roundNumber","pickInRound","memberId","sportTeamId") VALUES (10,3,2,1,12,102)');expire()
        assert service.process_timeout_for_job(10)['nextMemberId']==11
        assert [r['memberId'] for r in state()['DraftTurn'][:4]]==[11,11,12,12]
        reset();final();expire();before=state();row=service.process_timeout_for_job(10)
        assert row['moved'] is False and state()['DraftTurn']==before['DraftTurn'] and state()['DraftState'][0]['expiresAt']>before['DraftState'][0]['expiresAt']
        reset();expire();query('DELETE FROM "DraftTurn" WHERE "leagueId"=10 AND "overallPickNumber"=2');before=state()
        expect(ValueError,lambda:service.process_timeout_for_job(10),'DraftTurn missing');assert state()==before
        for fragment in ('UPDATE "DraftTurn"','UPDATE "DraftState"'):
            reset();expire();failure_after(fragment,lambda:service.process_timeout_for_job(10))
        # Exhaust conference bucket (already drafted) then independent; sport/season/ownership/cap filters.
        reset();auto()
        with patch('endpoints.draft.pick_service.secrets.choice',side_effect=lambda choices:choices[0]):row=service.process_timeout_for_job(10)
        assert row['sportTeamId']==102 and state()['DraftState'][0]['currentOverallPickNumber']==3
        assert state()['LeagueTeamSlot'][0]['acquiredWeek']==1 and messages()
        reset();auto();query('INSERT INTO "LeagueTeamSlot" ("leagueId","memberId","sportTeamId","acquiredWeek") VALUES (10,11,102,1)');before=state()
        assert service.process_timeout_for_job(10) is None and state()==before
        reset();auto();query('INSERT INTO "SportTeam" VALUES (104,1,\'Conference Candidate\')');query('INSERT INTO "ConferenceMembership" VALUES (104,1,NULL,501)')
        query('UPDATE "SportConference" SET "maxTeamsPerOwner"=1');query('INSERT INTO "LeagueTeamSlot" ("leagueId","memberId","sportTeamId","acquiredWeek") VALUES (10,12,101,1)')
        with patch('endpoints.draft.pick_service.secrets.choice',side_effect=lambda choices:choices[0]):assert service.process_timeout_for_job(10)['sportTeamId']==102
        reset();auto();final();row=service.process_timeout_for_job(10);notified=messages()
        assert row['draftComplete'] is True and notified,(row,notified)
        for fragment in ('INSERT INTO "DraftPick"','INSERT INTO "LeagueTeamSlot"','"lastPickAt" = now()','pg_notify'):
            reset();auto();failure_after(fragment,lambda:service.process_timeout_for_job(10))
        # Real lock contention: a trusted live pick with NULL expiry holds state; timeout waits, re-reads
        # the advanced unexpired pointer and performs no second transition. No worker process is started.
        reset();query('UPDATE "DraftState" SET "expiresAt"=NULL WHERE "leagueId"=10')
        locked=threading.Event();release=threading.Event();errors=[];results={};other=engine_for(database,'otm-pick-contender')
        def hold(conn,cursor,statement,params,context,many):
            if 'FOR UPDATE' in statement and '"expiresAt"' in statement:locked.set();assert release.wait(5)
        event.listen(engine,'after_cursor_execute',hold)
        def live_pick():
            try:results['pick']=service.pick_live_for_job(10,12,102)
            except BaseException as exc:errors.append(exc)
        def timeout():
            try:results['timeout']=DraftPickService(other).process_timeout_for_job(10)
            except BaseException as exc:errors.append(exc)
        first=threading.Thread(target=live_pick);second=threading.Thread(target=timeout)
        try:
            first.start();assert locked.wait(5);second.start()
            # A second connection must actually be waiting on the row lock, not merely scheduled late.
            for _ in range(200):
                wait=query("SELECT wait_event_type FROM pg_stat_activity WHERE application_name='otm-pick-contender'")
                if wait and wait[0]['wait_event_type']=='Lock':break
                threading.Event().wait(.01)
            else:raise AssertionError('Native state contention was not observed')
            release.set();first.join(5);second.join(5)
            assert not first.is_alive() and not second.is_alive() and not errors,errors
            assert results['timeout'] is None and results['pick']['overallPickNumber']==2 and len(state()['LeagueTeamSlot'])==1
        finally:
            release.set();first.join(5)
            if second.ident:second.join(5)
            event.remove(engine,'after_cursor_execute',hold);other.dispose()
        # Execute worker deadline helper extracted without importing configured db or launching worker.
        reset();source=ast.parse((ROOT/'api/worker/draftTimeoutWorker.py').read_text())
        helper=next(n for n in source.body if isinstance(n,ast.FunctionDef) and n.name=='_get_next_expired_or_soonest_deadline')
        from typing import Optional,Tuple
        namespace={'Optional':Optional,'Tuple':Tuple,'DraftPickRepository':lambda:repo}
        exec(compile(ast.Module(body=[helper],type_ignores=[]),'<isolated-worker-deadline>','exec'),namespace)
        with engine.begin() as conn:
            deadline=namespace[helper.name](conn);assert deadline[0]==10 and 0<deadline[1]<=60
        query('UPDATE "DraftState" SET status=\'paused\'')
        with engine.begin() as conn:assert namespace[helper.name](conn) is None
        reset();legacy=DraftModel.__new__(DraftModel);legacy.db=engine
        assert legacy.create_draft_pick_live(10,12,102)['overallPickNumber']==2
        declared={name for name,method in vars(DraftPickRepository).items() if callable(method) and not name.startswith('_')}
        assert covered==declared,{'missing_native_operations':sorted(declared-covered)}
        return {'native_live_manual_lookup_ownership_turn_grace_caps_season_defaults':'PASS',
                'guarded_insert_rechecks_separate_transaction_revocation':'PASS',
                'native_skip_rotation_unpicked_holes_last_turn_missing_turn_and_noops':'PASS',
                'native_auto_random_buckets_caps_availability_sport_and_completion':'PASS',
                'post_write_finalize_notify_statement_deferred_commit_rollback':'PASS',
                'real_pick_timeout_lock_wait_rechecks_advanced_clock':'PASS',
                'native_worker_deadline_without_worker_startup':'PASS',
                'postgres_notify_commit_only_existing_branch_placement':'PASS',
                'repository_queries_exercised':sorted(covered),
                'scope_limit':'Original publication placement, restart and legacy cap/random policies preserved; this is extraction, not MOD-023/025/startup redesign'}
    finally:listener.close()


def main():
    admin=psycopg2.connect(dbname='postgres',**LOCAL);admin.autocommit=True
    database='otm_draft_complete_'+uuid4().hex;created=False;engine=None
    try:
        with admin.cursor() as cursor:
            cursor.execute("SELECT shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()")
            assert cursor.fetchone()[0]=='otm-modernization-assessment-20261029-synthetic-only','Refusing unmarked server'
            cursor.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(database)));created=True
        engine=engine_for(database,'otm-draft-complete')
        if 'timeout-probe' in sys.argv:
            print(tests(engine,database,probe=True));return
        draft=tests(engine,database)
        previous={'snapshot':snapshot_tests(engine,database),'finalization':finalize_tests(engine,database),
                  'controls':control_tests(engine,database),'order':order_tests(engine,database)}
        files=['api/endpoints/draft/'+name for name in ('draft_rules.py','pick_service.py','pick_repository.py','control_service.py',
            'control_repository.py','snapshot_service.py','snapshot_repository.py','draftModel.py','draftEndpoints.py','routes.py','draftSocket.py','startDraftNotifyListener.py','notifyChannel.py')]
        files+=['api/actors.py','api/worker/draftTimeoutWorker.py']
        files+=['scripts/modernization/'+name for name in ('verify_draft_snapshot.py','verify_draft_finalization.py','verify_draft_controls.py','verify_draft_order.py','verify_draft_complete.py')]
        report={'result':'PASS','scope':'Synthetic marked loopback PostgreSQL only; no configured DB or running jobs/listeners',
                'remaining_draft':draft,'previous_slices_rerun':previous,
                'sha256':{name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in files}}
        (ROOT/'docs/modernization/evidence/mod-038-draft-complete-postgres-2026-10-30.json').write_text(json.dumps(report,indent=2)+'\n')
        print(json.dumps(report,indent=2))
    finally:
        if engine is not None:engine.dispose()
        if created:
            with admin.cursor() as cursor:cursor.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(database)))
        admin.close()

if __name__=='__main__':main()
