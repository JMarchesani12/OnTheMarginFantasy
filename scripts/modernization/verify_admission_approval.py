def tests(engine, database):
    service = AdmissionService(engine)
    actor = UserActor(1, 'alice')

    def reset():
        with engine.begin() as conn: conn.exec_driver_sql(FIXTURE)

    def state():
        with engine.connect() as conn:
            return {table: [dict(row._mapping) for row in conn.execute(text(f'SELECT * FROM "{table}" ORDER BY id'))]
                    for table in ('League', 'LeagueMember', 'LeagueJoinRequest')}

    reset()
    before = state()
    for who, league, request, error in ((UserActor(2, 'bob'),10,101,AdmissionDenied),
            (actor,999,101,AdmissionRejected),(actor,10,201,AdmissionRejected),
            (actor,10,103,AdmissionRejected),(actor,10,999,AdmissionRejected)):
        try: service.approve_request(who, league, request)
        except error: pass
        else: raise AssertionError('Approval authority/scope/state bypass')
        assert state() == before
    result = service.approve_request(actor, 10, 101)
    assert set(result) == {'request', 'member'}
    assert set(result['request']) == {'id','createdAt','leagueId','userId','status','message','resolvedAt','resolvedByUserId'}
    assert set(result['member']) == {'id','leagueId','userId','teamName','seasonPoints','createdAt'}
    assert (result['request']['status'],result['request']['resolvedByUserId']) == ('APPROVED',1)
    assert result['request']['resolvedAt'] is not None and result['member']['createdAt'] is not None
    after = state()
    assert (after['League'][0]['numPlayers'],after['League'][0]['settings']) == (3,{'draft':{'numberOfRounds':7},'timezone':'UTC'})
    assert (after['LeagueMember'][-1]['draftOrder'],result['member']['seasonPoints']) == (3,0)
    try: service.approve_request(actor, 10, 101)
    except AdmissionRejected: pass
    else: raise AssertionError('Approval replay accepted')
    assert state() == after

    # Pin actual jsonb_set behavior: an absent parent is not implicitly created.
    for setting, players, expected in ((None,2,{}),({'timezone':'UTC'},2,{'timezone':'UTC'}),
            ({'draft':{},'keep':True},20,{'draft':{'numberOfRounds':1},'keep':True}),
            ({'draft':{'numberOfRounds':9}},0,{'draft':{'numberOfRounds':8}})):
        reset()
        with engine.begin() as conn:
            conn.execute(text('UPDATE "League" SET settings=CAST(:settings AS jsonb),"numPlayers"=:players WHERE id=10'),
                         {'settings':json.dumps(setting) if setting is not None else None,'players':players})
            conn.execute(text('UPDATE "LeagueJoinRequest" SET "teamName"=NULL WHERE id=101'))
        result = service.approve_request(actor,10,101)
        assert result['member']['teamName'] == 'My Team'
        assert state()['League'][0]['settings'] == expected

    # Real uniqueness and resolver-FK errors retain operational failure semantics.
    for duplicate in (True,False):
        reset()
        if duplicate:
            with engine.begin() as conn: conn.execute(text('UPDATE "LeagueJoinRequest" SET "userId"=2 WHERE id=101'))
        before = state()
        try:
            if duplicate: service.approve_request(actor,10,101)
            else: service.approve_request_for_job(10,101,999)
        except DBAPIError: pass
        else: raise AssertionError('Native unique/FK failure missing')
        assert state() == before

    # Fail after each actual mutation; none of membership/count/resolution may survive.
    for fragment in ('INSERT INTO "LeagueMember"','WITH locked_league AS','UPDATE "LeagueJoinRequest"'):
        reset(); before = state()
        def fail(conn,cursor,statement,params,context,many):
            if fragment in statement: raise RuntimeError('synthetic post-write failure')
        event.listen(engine,'after_cursor_execute',fail)
        try:
            try: service.approve_request(actor,10,101)
            except RuntimeError: pass
            else: raise AssertionError('Post-write failure missing')
        finally: event.remove(engine,'after_cursor_execute',fail)
        assert state() == before
    reset(); before = state()
    with engine.begin() as conn:
        conn.exec_driver_sql('''CREATE FUNCTION fail_approval_commit() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN RAISE EXCEPTION 'synthetic deferred approval failure'; END $$;
            CREATE CONSTRAINT TRIGGER approval_commit AFTER UPDATE ON "LeagueJoinRequest"
            DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fail_approval_commit();''')
    try: service.approve_request(actor,10,101)
    except DBAPIError: pass
    else: raise AssertionError('Deferred approval failure missing')
    assert state() == before

    concurrency = []
    for facade in (False,True):
        for same in (True,False):
            reset()
            first = engine_for(database,'otm-approve-first'); second = engine_for(database,'otm-approve-second')
            locked, release = threading.Event(), threading.Event()
            outcomes, locks = {}, []
            def hold(conn,cursor,statement,params,context,many):
                if 'FOR UPDATE' in statement and 'WITH locked_league AS' not in statement:
                    locks.append('request' if '"LeagueJoinRequest"' in statement else 'league')
                    if len(locks) == 1:
                        locked.set()
                        if not release.wait(10): raise RuntimeError('Synthetic approval lock timeout')
            event.listen(first,'after_cursor_execute',hold)
            def approve(label,owner,request):
                try:
                    if facade:
                        model = LeagueModel.__new__(LeagueModel); model.db = owner
                        row = model.approve_join_request_as_commissioner(10,request,1)
                    else: row = AdmissionService(owner).approve_request(actor,10,request)
                    outcomes[label] = ['success',row['request']['status'],row['request']['resolvedByUserId']]
                except Exception as exc: outcomes[label] = [type(exc).__name__,str(exc)]
            a = threading.Thread(target=approve,args=('first',first,101),daemon=True)
            b = threading.Thread(target=approve,args=('second',second,101 if same else 102),daemon=True)
            a.start()
            try:
                assert locked.wait(5),'First approval failed to lock league'
                b.start(); blocked = False; deadline = time.monotonic()+5
                while time.monotonic() < deadline:
                    with engine.connect() as conn:
                        blocked = conn.execute(text("SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE application_name='otm-approve-second' AND wait_event_type='Lock' AND cardinality(pg_blocking_pids(pid))>0)")).scalar_one()
                    if blocked: break
                    time.sleep(.02)
                assert blocked,'Competing approval did not wait on lock'
            finally:
                release.set(); a.join(10)
                if b.ident is not None: b.join(10)
                event.remove(first,'after_cursor_execute',hold)
                first.dispose(); second.dispose()
            assert not a.is_alive() and not b.is_alive()
            assert locks == ['league','request'],locks
            assert outcomes['first'] == ['success','APPROVED',1],outcomes
            assert outcomes['second'] == ([('ValueError' if facade else 'AdmissionRejected'),'Join request is not pending'] if same else ['success','APPROVED',1]),outcomes
            final = state(); new_members = [r for r in final['LeagueMember'] if r['leagueId']==10 and r['userId'] in (3,4)]
            assert sorted(r['draftOrder'] for r in new_members) == ([3] if same else [3,4])
            assert final['League'][0]['numPlayers'] == (3 if same else 4)
            assert final['League'][0]['settings'] == {'draft':{'numberOfRounds':7 if same else 6},'timezone':'UTC'}
            concurrency.append({'path':'legacy_facade' if facade else 'service','requests':'same' if same else 'distinct',
                                'observed_lock_wait':True,'lock_order':locks,'outcomes':outcomes})
    reset()
    model = LeagueModel.__new__(LeagueModel); model.db = engine
    assert model.approve_join_request(10,101,5)['request']['resolvedByUserId'] == 5
    with engine.begin() as conn:
        assert model._approve_join_request(conn,20,201,5)['request']['resolvedByUserId'] == 5
    return {'authority_scope_state_projection_resolver':'PASS','capacity_json_rounds_fallback':'PASS',
            'real_unique_fk_rollback':'PASS','all_post_write_and_commit_rollback':'PASS',
            'trusted_supplied_connection_compatibility':'PASS','concurrent_approval':concurrency}


