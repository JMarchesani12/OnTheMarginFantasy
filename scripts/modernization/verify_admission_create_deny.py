def current_tests(engine,database):
    with engine.begin() as conn:conn.exec_driver_sql(FIXTURE)
    service=AdmissionService(engine)
    def state():
        with engine.connect() as conn:return [dict(r._mapping) for r in conn.execute(text('SELECT * FROM "LeagueJoinRequest" ORDER BY id'))]
    bob=service.create_request(UserActor(2,'bob'),10,'First',' New ')
    assert set(bob)=={'id','createdAt','leagueId','userId','status','message','resolvedAt','resolvedByUserId'}
    assert service.create_request(UserActor(2,'bob'),10,'Replacement','Different')==bob
    assert (state()[0]['teamName'],state()[0]['message'])==('New','First')
    try:service.create_request(UserActor(2,'bob'),20,team_name='Member')
    except AdmissionRejected:pass
    else:raise AssertionError('Member requested admission')
    before=state()
    for league,name in ((10,'fail-statement'),(10,'fail-commit'),(999,'Missing league')):
        try:service.create_request(UserActor(3,'other'),league,team_name=name)
        except DBAPIError:pass
        else:raise AssertionError('Native insert/FK/commit failure did not abort')
        assert state()==before
    other=service.create_request(UserActor(3,'other'),10,team_name='Other')
    foreign=service.create_request(UserActor(1,'alice'),20,team_name='Foreign')
    before=state()
    for actor,league,request,error in ((UserActor(2,'bob'),10,bob['id'],AdmissionDenied),
        (UserActor(1,'alice'),10,foreign['id'],AdmissionRejected),(UserActor(1,'alice'),999,bob['id'],AdmissionRejected)):
        try:service.deny_request(actor,league,request)
        except error:pass
        else:raise AssertionError('Invalid denial allowed')
        assert state()==before
    def fail_update(conn,cursor,statement,params,context,many):
        if 'UPDATE "LeagueJoinRequest"' in statement:raise RuntimeError('synthetic after-denial update')
    event.listen(engine,'after_cursor_execute',fail_update)
    try:
        try:service.deny_request(UserActor(1,'alice'),10,bob['id'])
        except RuntimeError:pass
        else:raise AssertionError('Post-update failure did not abort')
    finally:event.remove(engine,'after_cursor_execute',fail_update)
    assert state()==before
    with engine.begin() as conn:
        conn.exec_driver_sql('''CREATE FUNCTION fail_deny_commit() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN IF NEW.status='DENIED' THEN RAISE EXCEPTION 'synthetic deferred denial failure'; END IF; RETURN NEW; END $$;
            CREATE CONSTRAINT TRIGGER deny_commit AFTER UPDATE ON "LeagueJoinRequest"
                DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fail_deny_commit();''')
    try:service.deny_request(UserActor(1,'alice'),10,bob['id'])
    except DBAPIError:pass
    else:raise AssertionError('Deferred denial failure did not abort')
    assert state()==before
    with engine.begin() as conn:conn.exec_driver_sql('DROP TRIGGER deny_commit ON "LeagueJoinRequest"')
    concurrent=[]
    for facade in (False,True):
        with engine.begin() as conn:
            conn.execute(text('UPDATE "LeagueJoinRequest" SET status=\'PENDING\',"resolvedAt"=NULL,"resolvedByUserId"=NULL WHERE id=:id'),{'id':bob['id']})
        first=engine_for(database,'otm-deny-first');second=engine_for(database,'otm-deny-second')
        locked,release=threading.Event(),threading.Event();outcomes={};locks=[]
        def hold(conn,cursor,statement,params,context,many):
            if 'FOR UPDATE' in statement:
                locks.append('request' if 'LeagueJoinRequest' in statement else 'league')
                if len(locks)==1:locked.set();assert release.wait(10),'First denial was not released'
        event.listen(first,'after_cursor_execute',hold)
        def deny(label,db):
            try:
                if facade:
                    model=LeagueModel.__new__(LeagueModel);model.db=db
                    result=model.deny_join_request_as_commissioner(10,bob['id'],1)
                else:result=AdmissionService(db).deny_request(UserActor(1,'alice'),10,bob['id'])
                outcomes[label]=['success',result['status'],result['resolvedByUserId']]
            except Exception as exc:outcomes[label]=[type(exc).__name__,str(exc)]
        a=threading.Thread(target=deny,args=('first',first));b=threading.Thread(target=deny,args=('second',second));a.start()
        try:
            assert locked.wait(5),'First denial did not lock league';b.start()
            blocked=False;deadline=time.monotonic()+5
            while time.monotonic()<deadline:
                with engine.connect() as conn:
                    blocked=conn.execute(text("SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE application_name='otm-deny-second' AND wait_event_type='Lock' AND cardinality(pg_blocking_pids(pid))>0)")).scalar_one()
                if blocked:break
                time.sleep(.02)
            assert blocked,'No competing denial lock wait observed'
        finally:
            release.set();a.join(10)
            if b.ident is not None:b.join(10)
            first.dispose();second.dispose()
        assert not a.is_alive() and not b.is_alive()
        assert locks==['league','request'],locks
        assert outcomes=={'first':['success','DENIED',1],
            'second':['ValueError' if facade else 'AdmissionRejected','Join request is not pending']},outcomes
        concurrent.append({'path':'legacy_facade' if facade else 'service','observed_lock_wait':True,'lock_order':locks,'outcomes':outcomes})
    model=LeagueModel.__new__(LeagueModel);model.db=engine
    legacy=model.deny_join_request(10,other['id'],4)
    assert (legacy['status'],legacy['resolvedByUserId'])==('DENIED',4)
    pending=service.create_request(UserActor(3,'other'),10,team_name='Private helper')
    with engine.begin() as conn:
        row=model._deny_join_request(conn,10,pending['id'],1)
        assert row['resolvedByUserId']==1
    return {'creation_projection_normalization_repeat':'PASS','membership_and_real_fk_failures':'PASS',
        'insert_statement_and_commit_rollback':'PASS','denial_authority_scope_and_resolver':'PASS',
        'denial_post_update_and_commit_rollback':'PASS','trusted_and_supplied_connection_compatibility':'PASS',
        'concurrent_denial':concurrent}


