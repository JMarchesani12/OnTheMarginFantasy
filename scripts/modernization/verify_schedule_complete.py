class SyntheticProvider(ESPNClient):
    """Actual event parser, replaced fetch methods only: never sends a request."""
    def __init__(self, url, keyword):
        super().__init__(url,keyword)
        self.calls=[];self.fail_group=None;self.fail_team=None;self.fail_dates=set()
    def payload(self, datestr, identity=None):
        day=dt.datetime.strptime(datestr,'%Y%m%d').date()
        return {'events':[{'id':identity or 'synthetic-'+datestr,'date':day.isoformat()+'T12:00:00Z',
            'season':{'type':2},'competitions':[{'broadcasts':[{'names':['Synthetic TV']}],
                'competitors':[{'homeAway':side,'team':{'id':team,'displayName':name},'score':score}
                    for side,team,name,score in [('home','101','Alpha','21'),('away','102','Beta','0')]]}]}]}
    def fetch_scoreboard_for_date(self, datestr, group_id):
        self.calls.append((datestr,group_id))
        if group_id==self.fail_group or datestr in self.fail_dates:raise OSError('synthetic provider failure')
        return self.payload(datestr)
    def fetch_team_schedule(self, team_id):
        self.calls.append(('team',team_id))
        if team_id==self.fail_team:raise OSError('synthetic team fetch failure')
        return self.payload('20261103','team-'+team_id)


