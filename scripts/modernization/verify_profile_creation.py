def creation_tests(engine):
    with engine.begin() as conn:
        conn.exec_driver_sql(FIXTURE)
    service=UserService(engine)
    def count():
        with engine.connect() as conn:
            return conn.execute(text('SELECT count(*) FROM "User"')).scalar_one()
    for actor,name,expected in (
        (ProfileSubject('00000000-0000-4000-8000-000000000001','alice@example.test'),'Overwrite',ProfileAlreadyExists),
        (ProfileSubject(AMBIGUOUS,'duplicate@example.test'),'Overwrite',ProfileIdentityAmbiguous),
        (ProfileSubject(NEW,'alice@example.test'),'Collision',ProfileCreationRejected),
        (ProfileSubject(MISSING,'missing@example.test'),'Missing FK',ProfileCreationRejected),
        (ProfileSubject(NEW,'new@example.test'),'fail-statement',ProfileCreationRejected),
        (ProfileSubject(NEW,'new@example.test'),'fail-commit',ProfileCreationRejected)):
        try:
            service.create_profile(actor,name)
        except expected:
            pass
        else:
            raise AssertionError(f'Expected {expected.__name__}')
        assert count()==3,'Failed or denied creation persisted a row'
    created=service.create_profile(ProfileSubject(NEW,' new@example.test ')," New O'Connor ")
    assert created['email']=='new@example.test' and created['displayName']=="New O'Connor",created
    assert str(created['uuid'])==NEW
    assert set(created)=={'id','createdAt','email','displayName','uuid'}
    assert service.get_profile_by_uuid_for_job(NEW)==created
    try:
        service.create_profile(ProfileSubject(NEW,'new@example.test'),'Repeat')
    except ProfileAlreadyExists:
        pass
    else:
        raise AssertionError('Repeat did not conflict')
    assert count()==4
    model=UserModel(engine)
    assert str(model.get_user_by_uuid(AMBIGUOUS)['uuid'])==AMBIGUOUS
    legacy=model.create_user(' legacy@example.test ',None,NEW)
    assert legacy['displayName']=='' and legacy['email']=='legacy@example.test'
    assert count()==5  # legacy trusted creation intentionally has no new UUID precheck
    try:
        model.create_user('alice@example.test','Duplicate',NEW)
    except ValueError as exc:
        assert str(exc)=='User creation failed'
    else:
        raise AssertionError('Legacy constraint failure did not translate')
    assert count()==5
    return {'creation_normalization_projection_reload':'PASS','existing_and_ambiguous_denials':'PASS',
            'real_email_unique_and_auth_fk':'PASS','insert_statement_rollback':'PASS',
            'deferred_insert_commit_rollback':'PASS','legacy_uuid_and_creation_compatibility':'PASS'}


def main():
    admin=psycopg2.connect(dbname='postgres',**LOCAL)
    admin.autocommit=True
    name='otm_creation_'+uuid4().hex
    created=False
    engine=None
    try:
        with admin.cursor() as cur:
            cur.execute("SELECT shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()")
            assert cur.fetchone()[0]=='otm-modernization-assessment-20261029-synthetic-only','Refusing unmarked server'
            cur.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(name)))
            created=True
        engine=engine_for(name,'otm-profile-creation')
        reads=profile_tests(engine)
        creations=creation_tests(engine)
        files=['api/endpoints/user/'+f for f in ('service.py','repository.py','contracts.py','userModel.py','userEndpoints.py')]
        files+=['api/actors.py','api/authenticatedPrincipal.py','scripts/modernization/verify_profile_pilot.py',
                'scripts/modernization/verify_profile_creation.py']
        report={'result':'PASS','scope':'Synthetic marked loopback PostgreSQL; auth.users is a minimal FK fixture, not provider acceptance',
                'profile_reads_updates_rerun':reads,'profile_creation_uuid':creations,
                'sha256':{f:hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in files}}
        (ROOT/'docs/modernization/evidence/mod-038-profile-creation-postgres-2026-10-29.json').write_text(json.dumps(report,indent=2)+'\n')
        print(json.dumps(report,indent=2))
    finally:
        if engine is not None:
            engine.dispose()
        if created:
            with admin.cursor() as cur:
                cur.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(name)))
        admin.close()


if __name__=='__main__':
    main()
