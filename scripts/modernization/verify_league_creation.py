FIXTURE='''DROP SCHEMA public CASCADE; CREATE SCHEMA public;
CREATE TABLE "User" (id bigint PRIMARY KEY); INSERT INTO "User" VALUES (1),(2);
CREATE TABLE "Sport" (id bigint PRIMARY KEY,name text); INSERT INTO "Sport" VALUES (1,'Basketball');
CREATE TABLE "League" (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"createdAt" timestamptz DEFAULT now(),
    name text,sport bigint,"numPlayers" integer,status text,settings jsonb,"updatedAt" timestamptz,"draftDate" timestamptz,
    commissioner bigint REFERENCES "User"(id),"seasonYear" integer,"isDiscoverable" boolean);
CREATE TABLE "LeagueMember" (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "leagueId" bigint REFERENCES "League"(id),"userId" bigint REFERENCES "User"(id),
    "teamName" text,"seasonPoints" integer,"draftOrder" integer);
CREATE TABLE "Week" (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"leagueId" bigint REFERENCES "League"(id));'''


def tests(engine,database):
    actor=UserActor(1,'alice');service=LeagueAdminService(engine);calls=[]
    def reset():
        calls.clear()
        with engine.begin() as conn:conn.exec_driver_sql(FIXTURE)
    def payload(**overrides):
        return dict(name="O'Brien :name",sport=1,numPlayers=8,status='Pre-Draft',settings={},draftDate=None,
                    commissioner=2,seasonYear=2026,isDiscoverable=True,teamName=' New Team ',**overrides)
    def state():
        with engine.connect() as conn:
            return {table:[dict(r._mapping) for r in conn.execute(text(f'SELECT * FROM "{table}" ORDER BY id'))]
                    for table in ('League','LeagueMember','Week')}
    observer=engine_for(database,'otm-create-initializer')
    def initialize(league_id):
        # Separate transaction proves creation is committed before capability call.
        with observer.begin() as conn:
            assert conn.execute(text('SELECT count(*) FROM "League" WHERE id=:id'),{'id':league_id}).scalar_one()==1
            assert conn.execute(text('SELECT count(*) FROM "LeagueMember" WHERE "leagueId"=:id'),{'id':league_id}).scalar_one()==1
            conn.execute(text('INSERT INTO "Week" ("leagueId") VALUES (:id)'),{'id':league_id})
        calls.append(league_id)
    try:
        reset();data=payload();snapshot=json.loads(json.dumps(data))
        row=service.create(actor,data,initialize)
        assert data==snapshot
        assert set(row)=={'id','createdAt','name','sport','numPlayers','status','settings','updatedAt','draftDate',
                          'commissioner','seasonYear','isDiscoverable','sportinfo','creatorMemberId'}
        assert row['commissioner']==1 and row['name']=="O'Brien :name" and row['isDiscoverable'] is True
        assert row['sportinfo']=={'id':1,'name':'Basketball'} and row['createdAt'] is not None and row['updatedAt'] is not None
        assert row['settings']=={'ruleSetVersion':'v1','timezone':'UTC'} and calls==[row['id']]
        assert state()['LeagueMember']==[{'id':row['creatorMemberId'],'leagueId':row['id'],'userId':1,
                                         'teamName':'New Team','seasonPoints':0,'draftOrder':1}]
        assert len(state()['Week'])==1
        reset();data=payload();data['settings']={'schedule':{'timeZone':'America/Chicago'}}
        assert service.create(actor,data,initialize)['settings']=={'ruleSetVersion':'v1','schedule':{'timeZone':'America/Chicago'}}
        for fragment in ('WITH created AS','INSERT INTO "LeagueMember"'):
            reset();before=state()
            def fail(conn,cursor,statement,params,context,many):
                if fragment in statement:raise RuntimeError('synthetic post-create-write failure')
            event.listen(engine,'after_cursor_execute',fail)
            try:
                try:service.create(actor,payload(),initialize)
                except RuntimeError:pass
                else:raise AssertionError('Post-write failure missing')
            finally:event.remove(engine,'after_cursor_execute',fail)
            assert state()==before and calls==[]
        reset();before=state()
        # No matching Sport projection must roll back the CTE's INSERT, as before.
        data=payload();data['sport']=999
        try:service.create(actor,data,initialize)
        except RuntimeError as exc:assert str(exc)=='Failed to create League'
        else:raise AssertionError('Missing creation projection guard')
        assert state()==before and calls==[]
        data=payload();data['commissioner']=999
        try:service.create_for_job(data,initialize)
        except DBAPIError:pass
        else:raise AssertionError('Actual commissioner FK restriction missing')
        assert state()==before and calls==[]
        with engine.begin() as conn:
            conn.exec_driver_sql('''CREATE FUNCTION invalid_member() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN NEW."userId"=999; RETURN NEW; END $$;
                CREATE TRIGGER invalid_member BEFORE INSERT ON "LeagueMember" FOR EACH ROW EXECUTE FUNCTION invalid_member();''')
        try:service.create(actor,payload(),initialize)
        except DBAPIError:pass
        else:raise AssertionError('Actual member FK restriction missing')
        assert state()==before and calls==[]
        reset();before=state()
        with engine.begin() as conn:
            conn.exec_driver_sql('''CREATE FUNCTION fail_create_commit() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN RAISE EXCEPTION 'synthetic deferred creation failure'; END $$;
                CREATE CONSTRAINT TRIGGER create_commit AFTER INSERT ON "LeagueMember"
                DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION fail_create_commit();''')
        try:service.create(actor,payload(),initialize)
        except DBAPIError:pass
        else:raise AssertionError('Deferred creation failure missing')
        assert state()==before and calls==[]
        reset()
        def failed_initializer(league_id):
            initialize(league_id)
            raise RuntimeError('synthetic post-commit scheduling failure')
        try:service.create(actor,payload(),failed_initializer)
        except RuntimeError:pass
        else:raise AssertionError('Initializer failure swallowed')
        assert all(len(rows)==1 for rows in state().values()) and len(calls)==1
        reset();model=LeagueModel.__new__(LeagueModel);model.db=engine
        class Schedule:
            ensure_weeks_for_league=staticmethod(initialize)
        model.scheduleModel=Schedule()
        row=model.create_league(payload())
        assert row['commissioner']==2 and state()['LeagueMember'][0]['userId']==2 and calls==[row['id']]
        return {'native_cte_json_projection_member_defaults':'PASS','input_identity_timezone':'PASS',
                'real_commissioner_member_fk_no_projection_post_write_commit_rollback':'PASS',
                'supplied_initializer_separate_connection_visibility':'PASS','initializer_failure_preserves_committed_creation':'PASS',
                'legacy_trusted_model':'PASS',
                'scope_limit':'Scheduling capability boundary verified; ScheduleModel algorithms unchanged, not reimplemented in fixture'}
    finally:observer.dispose()


def main():
    admin=psycopg2.connect(dbname='postgres',**LOCAL);admin.autocommit=True
    name='otm_league_creation_'+uuid4().hex;created=False;engine=None
    try:
        with admin.cursor() as cur:
            cur.execute("SELECT shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()")
            assert cur.fetchone()[0]=='otm-modernization-assessment-20261029-synthetic-only','Refusing unmarked server'
            cur.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(name)));created=True
        engine=engine_for(name,'otm-league-creation')
        prior={'listing_cancellation':listing_tests(engine,name),'creation_denial':creation_tests(engine,name),
               'approval':approval_tests(engine,name),'member_profile':profile_tests(engine,name),'member_removal':removal_tests(engine,name),'league_deletion':deletion_tests(engine,name),'league_settings':settings_tests(engine,name)}
        creation=tests(engine,name)
        files=['api/endpoints/league/'+f for f in ('administration/service.py','administration/repository.py','members/service.py','members/repository.py','admission/service.py','admission/repository.py','admission/contracts.py','leagueModel.py','leagueEndpoints.py')]
        files+=['api/actors.py','api/rules/leagueRules.py']+['scripts/modernization/'+f for f in ('verify_admission_slice.py','verify_admission_create_deny.py','verify_admission_approval.py','verify_member_profile.py','verify_member_removal.py','verify_league_delete.py','verify_league_settings.py','verify_league_creation.py')]
        report={'result':'PASS','scope':'Synthetic marked loopback PostgreSQL; no configured/hosted database','prior_slices_rerun':prior,
                'league_creation':creation,'sha256':{f:hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in files}}
        (ROOT/'docs/modernization/evidence/mod-038-league-creation-postgres-2026-10-30.json').write_text(json.dumps(report,indent=2)+'\n')
        print(json.dumps(report,indent=2))
    finally:
        if engine is not None:engine.dispose()
        if created:
            with admin.cursor() as cur:cur.execute(sql.SQL('DROP DATABASE {} WITH (FORCE)').format(sql.Identifier(name)))
        admin.close()

if __name__=='__main__':main()
